def release_binding(out_dir) -> dict:
    """Identifiers of the current release, used by the benchmark and DoA generators to bind their reports."""
    info = json.loads((Path(out_dir) / "deliverables" / "export_info.json").read_text(encoding="utf-8"))
    return {k: info[k] for k in ("model_sha256", "tflite_sha256", "manifest_sha256")}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    h = sub.add_parser("headers")
    m = sub.add_parser("model")
    m.add_argument("--model", default=None)
    m.add_argument("--threshold", default=None)
    c = sub.add_parser("card")
    r = sub.add_parser("reset-test-record", help="document a reason in the ledger, then remove the test-consumption record and bundles")
    r.add_argument("--reason", required=True)
    for p in (h, m, c, r):
        p.add_argument("--config", default=None)
    args = ap.parse_args(argv)
    cfg = resolve(load_config(args.config))
    out = Path(cfg["paths"]["out_dir"])
    if args.cmd == "headers":
        thr = out / "deployed" / "threshold.json"
        tau = json.loads(thr.read_text())["tau"] if thr.exists() else 0.65
        write_headers_only(GEN_DIR, out / "deliverables" / "golden", FsmParams.from_config(tau, cfg["fsm"]), DoaParams(spacing_m=float(cfg["doa"]["spacing_m"])))
        print(f"headers -> {GEN_DIR}; golden -> {out / 'deliverables' / 'golden'}")
    elif args.cmd == "model":
        info = export_model(cfg, args.model, args.threshold)
        print(json.dumps({k: info[k] for k in ("model_version", "tau", "tflite_bytes", "params", "parity", "test")}, indent=1))
    elif args.cmd == "reset-test-record":
        ledger = reset_test_record(out, args.reason)
        print(f"reason recorded in {ledger}; record and bundles removed. The next `export model` evaluates the test split once more.")
    else:
        text = model_card(cfg)
        (out / "deliverables" / "model_card.md").write_text(text, encoding="utf-8")
        if (out / RESET_LEDGER).exists():
            shutil.copy(out / RESET_LEDGER, out / "deliverables" / RESET_LEDGER)  # ships with the card
        print(text[:2000])


if __name__ == "__main__":
    main()
