class ExportError(RuntimeError):
    """A release gate failed; nothing was promoted."""


def check_threshold_binding(model_path, thr: dict) -> str:
    from v5.train import file_sha256

    expected = thr.get("model_sha256")
    actual = file_sha256(model_path)
    if not expected or expected != actual:
        raise ExportError(f"threshold.json is bound to model sha256 {expected}, but {model_path} has {actual}; re-run `python -m v5.train final`")
    return actual


def _write_json_atomic(path: Path, payload: dict) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    os.replace(tmp, path)


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def bundle_hashes(bundle_dir: Path) -> dict:
    """SHA-256 of every file of an evaluation bundle, keyed by its path inside the bundle."""
    return {str(p.relative_to(bundle_dir)): _sha256_bytes(p.read_bytes()) for p in sorted(bundle_dir.rglob("*")) if p.is_file()}


RESET_LEDGER = "test_consumption_resets.log"  # persistent, next to the record; every reset reason lands here before anything is deleted


def _ledger_entries(out_dir: Path) -> list[tuple[datetime, str]]:
    path = Path(out_dir) / RESET_LEDGER
    if not path.exists():
        return []
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        stamp = line.split(" ", 1)[0]
        try:
            out.append((datetime.fromisoformat(stamp).replace(tzinfo=None), line))
        except ValueError:
            continue
    return out


def reset_test_record(out_dir, reason: str) -> Path:
    """The only sanctioned way to evaluate the test split again: the reason is appended to the ledger
    (printed in the model card) before the record and every evaluation bundle are removed."""
    out_dir = Path(out_dir)
    if not reason or len(reason.strip()) < 10:
        raise ExportError("a reset needs a reason of at least 10 characters; it is printed in the model card")
    ledger = out_dir / RESET_LEDGER
    with open(ledger, "a", encoding="utf-8") as fh:
        fh.write(f"{datetime.now().isoformat(timespec='seconds')} reset: {reason.strip()}\n")
    record, bundles = out_dir / "test_consumption.json", out_dir / "test_evaluation"
    if record.exists():
        record.unlink()
    if bundles.exists():
        shutil.rmtree(bundles)
    return ledger


def _require_documented_reset(out_dir: Path, reset_hint: str) -> None:
    """A fresh claim is refused while evidence of an earlier evaluation exists without a later ledger entry."""
    bundles = out_dir / "test_evaluation"
    if bundles.exists() and any(bundles.iterdir()):
        raise ExportError(f"evaluation bundles exist in {bundles} without a record; a fresh evaluation needs a documented reset. " + reset_hint)
    info = out_dir / "deliverables" / "export_info.json"
    if info.exists():
        try:
            exported_at = datetime.fromisoformat(json.loads(info.read_text(encoding="utf-8")).get("exported_at", "")).replace(tzinfo=None)
        except (ValueError, TypeError):
            exported_at = datetime.min
        if not any(stamp >= exported_at and " reset: " in line for stamp, line in _ledger_entries(out_dir)):
            raise ExportError(f"a release exported at {exported_at.isoformat(timespec='seconds')} exists but the ledger {out_dir / RESET_LEDGER} has no reset entry after it; "
                              "the earlier test evaluation must be reset with a documented reason first. " + reset_hint)


def claim_test_split(out_dir, manifest_sha: str, model_sha: str, tau: float):
    """Enforce the one-time test evaluation.

    Returns None when this model may evaluate the test split now (a fresh record is written), or the
    completed evaluation bundle when the same model re-exports at the same threshold. Raises for another
    model or manifest, another tau (the bundle's metrics and parity agreement are tau-specific), a bundle
    whose files differ from the hashes in the record, and an incomplete record left by an interrupted attempt."""
    out_dir = Path(out_dir)
    record = out_dir / "test_consumption.json"
    reset_hint = ("If that is a deliberate decision, run `python -m v5.export reset-test-record --reason '...'`: it writes the reason "
                  f"to {out_dir / RESET_LEDGER} (printed in the model card) and only then removes {record.name} and the evaluation bundles.")
    if not record.exists():
        _require_documented_reset(out_dir, reset_hint)
    if record.exists():
        prev = json.loads(record.read_text(encoding="utf-8"))
        if prev["manifest_sha256"] != manifest_sha:
            raise ExportError(f"the test split was consumed on manifest {prev['manifest_sha256'][:12]} by model {prev['model_sha256'][:12]} on {prev['at']}; "
                              "a rebuilt manifest does not grant a fresh evaluation. " + reset_hint)
        if prev["model_sha256"] != model_sha:
            raise ExportError(f"the test split of this manifest was already consumed by model {prev['model_sha256'][:12]} on {prev['at']}; "
                              "evaluating another model would turn the test set into a development set. " + reset_hint)
        bundle_dir = out_dir / "test_evaluation" / model_sha
        if not prev.get("complete") or not (bundle_dir / "results.json").exists():
            raise ExportError(f"a previous evaluation of model {model_sha[:12]} was interrupted before its bundle was completed; "
                              "the record is locked. " + reset_hint)
        if prev.get("tau") != tau:
            raise ExportError(f"the test split was evaluated at tau {prev.get('tau')} but the deployed threshold is now {tau}; the bundle's metrics and parity "
                              "agreement hold only at the evaluated tau, and a re-calibrated model may not read the test split again. " + reset_hint)
        expected = prev.get("bundle")
        actual = bundle_hashes(bundle_dir)
        if not expected or actual != expected:
            changed = sorted(set(expected or {}) ^ set(actual) | {k for k in (expected or {}) if actual.get(k) != expected[k]})
            raise ExportError(f"evaluation bundle {bundle_dir} does not match the hashes in {record} ({changed or 'no hashes recorded'}); "
                              "its results cannot be trusted. " + reset_hint)
        results = json.loads((bundle_dir / "results.json").read_text(encoding="utf-8"))
        if results.get("tflite_sha256") != expected.get("snore_v5_int8.tflite") or results.get("tau") != tau:
            raise ExportError(f"evaluation bundle {bundle_dir} is internally inconsistent; its results cannot be trusted. " + reset_hint)
        results["bundle_dir"] = str(bundle_dir)
        return results
    _write_json_atomic(record, {"manifest_sha256": manifest_sha, "model_sha256": model_sha, "tau": tau, "at": datetime.now().isoformat(timespec="seconds"), "complete": False})
    return None


def persist_test_results(out_dir, results: dict, tflite: bytes, golden_files: dict) -> Path:
    """Write the immutable evaluation bundle (staged, then renamed), then complete the record with the hash of every bundle file."""
    out_dir = Path(out_dir)
    record = out_dir / "test_consumption.json"
    prev = json.loads(record.read_text(encoding="utf-8"))
    final = out_dir / "test_evaluation" / prev["model_sha256"]
    if final.exists() or prev.get("complete"):
        raise ExportError(f"evaluation bundle {final} already exists; a completed evaluation is immutable")
    results = {**results, "tflite_sha256": _sha256_bytes(tflite), "tau": prev["tau"]}  # computed here, never trusted from the caller
    tmp = final.with_name(final.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    (tmp / "golden").mkdir(parents=True)
    (tmp / "snore_v5_int8.tflite").write_bytes(tflite)
    for name, data in golden_files.items():
        (tmp / "golden" / name).write_bytes(data)
    (tmp / "results.json").write_text(json.dumps(results, indent=1), encoding="utf-8")
    os.rename(tmp, final)
    prev["bundle"] = bundle_hashes(final)
    prev["complete"] = True
    _write_json_atomic(record, prev)
    return final


def check_manifest_binding(thr: dict, metrics: dict, manifest_sha: str) -> None:
    """The deployed model and its threshold must have been selected and calibrated on the manifest being exported."""
    for name, d in (("threshold.json", thr), ("deployed metrics.json", metrics)):
        if d.get("manifest_sha256") != manifest_sha:
            raise ExportError(f"{name} is bound to manifest {str(d.get('manifest_sha256'))[:12]} but the current manifest is {manifest_sha[:12]}; "
                              "re-run `python -m v5.train final` on this manifest")


