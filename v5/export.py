RELEASE_BOUND_REPORTS = ("model_card.md", "benchmark_nights.md", "doa_sim.md", "cross_collection.md")  # derived from a release; regenerated after every export


def _build_new_tree(live: Path, new: Path, stage: Path, files, golden: bool, drop=()) -> None:
    if new.exists():
        shutil.rmtree(new)
    if live.exists():
        shutil.copytree(live, new)
    else:
        new.mkdir(parents=True)
    for name in drop:  # a report bound to the previous release must not survive next to a new export_status "ok"
        if (new / name).exists():
            (new / name).unlink()
    for name in files:
        shutil.copy(stage / name, new / name)
    if golden:
        if (new / "golden").exists():
            shutil.rmtree(new / "golden")
        shutil.copytree(stage / "golden", new / "golden")


def promote(stage, deliv, gen_dir) -> None:
    """Transactional promotion: complete sibling trees are built first, then both live directories
    are swapped by rename; any failure rolls both back to the previous release."""
    stage, deliv, gen_dir = Path(stage), Path(deliv), Path(gen_dir)
    new_deliv, new_gen = deliv.with_name(deliv.name + ".new"), gen_dir.with_name(gen_dir.name + ".new")
    _build_new_tree(deliv, new_deliv, stage, PROMOTED_FILES, golden=True, drop=RELEASE_BOUND_REPORTS)
    _build_new_tree(gen_dir, new_gen, stage, HEADER_FILES, golden=False)
    swapped = []  # (live, bak): bak is None when there was no previous release; installed lives are removed on rollback
    try:
        for live, new in ((deliv, new_deliv), (gen_dir, new_gen)):
            bak = live.with_name(live.name + ".bak")
            if bak.exists():
                shutil.rmtree(bak)
            if live.exists():
                os.rename(live, bak)
                swapped.append((live, bak))
            else:
                swapped.append((live, None))
            os.rename(new, live)
    except Exception:
        for live, bak in reversed(swapped):
            if live.exists():  # partially or newly installed tree: never leave it behind
                shutil.rmtree(live)
            if bak is not None and bak.exists():
                os.rename(bak, live)
        for new in (new_deliv, new_gen):
            if new.exists():
                shutil.rmtree(new)
        raise
    for _, bak in swapped:  # post-commit cleanup is best-effort: the new release is already live
        if bak is not None and bak.exists():
            try:
                shutil.rmtree(bak)
            except OSError as exc:
                print(f"[export] warning: could not remove backup {bak}: {exc}")


